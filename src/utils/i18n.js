export function getFieldLabel(fieldId, t) {
  const map = {
    lastName: t.lastName,
    firstName: t.firstName,
    phone: t.phone,
    birthday: t.birthday,
    city: t.address,
    metAt: t.metAt,
    job: t.job,
    company: t.company,
    email: t.emailField,
    notes: t.notes,
  };
  return map[fieldId] || null;
}

